// which lazyBtRun's checks and btAsmSetup make valid for every ip of the
// block. Returns R0 = ml (below 4: none; -1: a tree entry at or after the
// position sorted or searched, impossible), R1 = offBase. Saves the lazy
// parser's R21-R26 across the call (an ABI0 function may clobber them).
