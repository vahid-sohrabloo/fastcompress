//go:build amd64 && !appengine && !noasm && !purego && gc

package zstd

import "github.com/vahid-sohrabloo/fastcompress/internal/cpu"

// useDubtAsm selects the assembly binary-tree loops (baseline amd64).
var useDubtAsm bool

// btAsmMls3: btGetAllNoDictAsm handles mls 3 (the hash3 table) here.
const btAsmMls3 = true

func init() {
	cpu.RegisterAsm("dubt", &useDubtAsm, func() bool { return true })
}

// insertDUBT1Asm is the loop of insertDUBT1Generic (see it) on the tree bt
// (pairs of entries, btMask+1 of them) over the input b, for position ip
// (index curr), with windowLow precomputed. It returns false, leaving the
// tree partially updated, if a candidate is not before ip (impossible: the
// tree only holds earlier positions).
//
// Preconditions (checked by insertDUBT1): len(bt) >= 2*(btMask+1);
// 0 <= ip < iend <= len(b); windowLow >= baseIdx, so every candidate
// (> windowLow) lies in b.
//
//go:noescape
func insertDUBT1Asm(bt *uint32, b *byte, ip, iend int, curr, baseIdx, btMask, nbCompares, btLow, windowLow uint32) bool

// dubtSearchAsm is dubtSearchGeneric's loop (see it), with the same
// preconditions as insertDUBT1Asm. matchEndIdx is 0 if a candidate was not
// before ip (impossible).
//
//go:noescape
func dubtSearchAsm(bt *uint32, b *byte, ip, iend int, curr, baseIdx, btMask, nbCompares, btLow, windowLow, matchIndex uint32) (bestLength int, offBase, matchEndIdx uint32)

// insertBt1Asm is insertBt1's tree walk (see it) from matchIndex, with the
// preconditions of insertDUBT1Asm (candidates are >= windowLow here). It
// returns bestLength and matchEndIdx; matchEndIdx is 0 if a candidate was
// not before ip (impossible).
//
//go:noescape
func insertBt1Asm(bt *uint32, b *byte, ip, iend int, curr, baseIdx, btMask, nbCompares, btLow, windowLow, matchIndex uint32) (bestLength int, matchEndIdx uint32)

// btGetAllNoDictAsm is btGetAllMatches (noDict, mls 3 to 6; see it) for
// the block set up in p, at ip, with ll0 = 1 for true: nothing in a
// skipped area, else the tree updated up to ip (updateTreeInternal) and
// insertBtAndGetAllMatches; see btGetAllNoDict and btGetAllMatchesFast for
// the preconditions. bad reports a tree entry at or after the position
// inserted or searched, or a full match table (both impossible).
//
//go:noescape
func btGetAllNoDictAsm(p *btAsmParams, ip int, rep *[repNum]uint32, ll0, lengthToBeat uint32) (mnum uint32, bad bool)

// dubtFindBestMatchAsm is dubtFindBestMatch (with updateDUBT; noDict) for
// the block set up in p, at ip; see dubtFindBestMatchFast for the
// preconditions. bad reports a tree entry at or after the position being
// sorted or searched (impossible).
//
//go:noescape
func dubtFindBestMatchAsm(p *btAsmParams, ip int) (bestLength int, offBase uint32, bad bool)

// lazyBt runs compressBlockLazyGeneric's match loop with the binary-tree
// finder (btlazy2, noDict) for the block set up in p by lazyBtRun, in
// zstd_lazy_bt_lazy_amd64.s (generated by zstd_lazy_gen_row_amd64.go); btSearch is its
// register-convention finder (never called from Go), which calls
// dubtFindBestMatchAsm.
//
//go:noescape
func lazyBt(p *rowAsmParams, seqs *seqDef, lits *byte, ip, anchor, iend, ilimit, prefixLowest int,
	rep1, rep2 uint32, depth int) (ipOut, anchorOut, nSeq, nLits int, rep1Out, rep2Out, llType, llPos uint32)
func btSearch()

// dubtExtAsmOK reports whether the extDict tree loops' assembly may run
// for a position whose segment ends at iend (BOUNDS in
// zstd_lazy_dubt_ext_amd64.s): baseIdx <= dictLimit, dictBaseIdx <=
// windowLow, the extDict within window.dictBase and iend within b.
func dubtExtAsmOK(ms *matchState, iend int, windowLow uint32) bool {
	w := &ms.window
	btMask := uint32(1)<<(ms.cParams.chainLog-1) - 1
	return useDubtAsm && len(ms.chainTable) >= 2*int(btMask+1) && len(w.base) > 0 && len(w.dictBase) > 0 &&
		iend <= len(w.base) && w.baseIdx <= w.dictLimit && w.dictBaseIdx <= windowLow &&
		w.dictLimit-w.dictBaseIdx <= uint32(len(w.dictBase))
}

// insertDUBT1ExtDict is insertDUBT1ExtDictGeneric, in assembly when
// dubtExtAsmOK.
func insertDUBT1ExtDict(ms *matchState, curr uint32, inputEnd int, nbCompares, btLow uint32) {
	w := &ms.window
	maxDistance := uint32(1) << ms.cParams.windowLog
	windowLow := w.lowLimit
	if curr-windowLow > maxDistance {
		windowLow = curr - maxDistance
	}
	if !dubtExtAsmOK(ms, inputEnd, windowLow) || (curr >= w.dictLimit && int(curr-w.baseIdx) >= inputEnd) {
		insertDUBT1ExtDictGeneric(ms, curr, inputEnd, nbCompares, btLow)
		return
	}
	btMask := uint32(1)<<(ms.cParams.chainLog-1) - 1
	if !insertDUBT1ExtAsm(&ms.chainTable[0], &w.base[0], &w.dictBase[0], inputEnd, curr, w.baseIdx, w.dictBaseIdx, w.dictLimit,
		btMask, nbCompares, btLow, windowLow) {
		panic("zstd: binary tree holds an index at or after the current position")
	}
}

// dubtSearchExtDict is dubtSearchExtDictGeneric, in assembly when
// dubtExtAsmOK.
func dubtSearchExtDict(ms *matchState, ip, iend int, curr, matchIndex, nbCompares, btLow, windowLow uint32) (int, uint32, uint32) {
	w := &ms.window
	if !dubtExtAsmOK(ms, iend, windowLow) || ip < 0 || ip >= iend || curr < w.dictLimit {
		return dubtSearchExtDictGeneric(ms, ip, iend, curr, matchIndex, nbCompares, btLow, windowLow)
	}
	btMask := uint32(1)<<(ms.cParams.chainLog-1) - 1
	best, offBase, matchEndIdx := dubtSearchExtAsm(&ms.chainTable[0], &w.base[0], &w.dictBase[0], iend, curr, w.baseIdx, w.dictBaseIdx, w.dictLimit,
		btMask, nbCompares, btLow, windowLow, matchIndex)
	if matchEndIdx == 0 {
		panic("zstd: binary tree holds an index at or after the current position")
	}
	ms.asmCalls++
	return best, offBase, matchEndIdx
}

// insertDUBT1ExtAsm is insertDUBT1ExtDictGeneric's loop over the prefix b
// and the extDict d (see the BOUNDS in zstd_lazy_dubt_ext_amd64.s,
// checked by insertDUBT1ExtDict). It returns false, leaving the tree
// partially updated, if a candidate is not before curr (impossible).
//
//go:noescape
func insertDUBT1ExtAsm(bt *uint32, b, d *byte, iend int, curr, baseIdx, dictBaseIdx, dictLimit, btMask, nbCompares, btLow, windowLow uint32) bool

// dubtSearchExtAsm is dubtSearchExtDictGeneric's loop, with the
// preconditions of insertDUBT1ExtAsm and the position in the prefix.
// matchEndIdx is 0 if a candidate was not before curr (impossible).
//
//go:noescape
func dubtSearchExtAsm(bt *uint32, b, d *byte, iend int, curr, baseIdx, dictBaseIdx, dictLimit, btMask, nbCompares, btLow, windowLow, matchIndex uint32) (bestLength int, offBase, matchEndIdx uint32)

// insertBt1ExtLoop runs insertBt1ExtDict's tree walk in assembly from
// matchIndex (hashTable already updated), returning bestLength and
// matchEndIdx, or ok = false (nothing done) when the assembly is off or a
// precondition fails (dubtExtAsmOK; the position in the prefix, before
// iend).
func insertBt1ExtLoop(ms *matchState, ip, iend int, curr, matchIndex, nbCompares, btLow, windowLow uint32) (int, uint32, bool) {
	w := &ms.window
	if !dubtExtAsmOK(ms, iend, windowLow) || ip < 0 || ip >= iend || curr < w.dictLimit {
		return 0, 0, false
	}
	btMask := uint32(1)<<(ms.cParams.chainLog-1) - 1
	bestLength, matchEndIdx := insertBt1ExtAsm(&ms.chainTable[0], &w.base[0], &w.dictBase[0], iend, curr, w.baseIdx, w.dictBaseIdx, w.dictLimit,
		btMask, nbCompares, btLow, windowLow, matchIndex)
	if matchEndIdx == 0 {
		panic("zstd: binary tree holds an index at or after the current position")
	}
	return bestLength, matchEndIdx, true
}

// btWalkExt runs insertBtAndGetAllMatchesExtDict's tree walk in assembly
// from matchIndex (hashTable already updated), appending to matches from
// mnum; it returns the new mnum and matchEndIdx, or ok = false (nothing
// done) when the assembly is off or a precondition fails (dubtExtAsmOK
// with matchLow; the position in the prefix, before iLimit).
func btWalkExt(matches *[optSize]optMatch, ms *matchState, ip, iLimit int, curr, matchIndex, nbCompares, btLow, matchLow, mnum uint32,
	bestLength int) (uint32, uint32, bool) {
	w := &ms.window
	if !dubtExtAsmOK(ms, iLimit, matchLow) || ip < 0 || ip >= iLimit || curr < w.dictLimit || mnum > optSize {
		return 0, 0, false
	}
	btMask := uint32(1)<<(ms.cParams.chainLog-1) - 1
	n, matchEndIdx, bad := btWalkExtAsm(&ms.chainTable[0], &w.base[0], &w.dictBase[0], &matches[0], iLimit, curr, w.baseIdx, w.dictBaseIdx, w.dictLimit,
		btMask, nbCompares, btLow, matchLow, matchIndex, mnum, bestLength)
	if bad {
		panic("zstd: binary tree holds an index at or after the current position")
	}
	ms.asmCalls++
	return n, matchEndIdx, true
}

// insertBt1ExtAsm is insertBt1ExtDict's tree walk, with the preconditions
// of insertDUBT1ExtAsm (candidates >= windowLow here) and the position in
// the prefix. matchEndIdx is 0 if a candidate was not before curr
// (impossible).
//
//go:noescape
func insertBt1ExtAsm(bt *uint32, b, d *byte, iend int, curr, baseIdx, dictBaseIdx, dictLimit, btMask, nbCompares, btLow, windowLow, matchIndex uint32) (bestLength int, matchEndIdx uint32)

// btWalkExtAsm is insertBtAndGetAllMatchesExtDict's tree walk (see
// btWalkExt), with the preconditions of insertBt1ExtAsm (matchLow for
// windowLow). bad reports a candidate not before curr, a full match table
// or a read past iLimit (all impossible).
//
//go:noescape
func btWalkExtAsm(bt *uint32, b, d *byte, matches *optMatch, iLimit int, curr, baseIdx, dictBaseIdx, dictLimit, btMask, nbCompares, btLow, matchLow, matchIndex, mnum uint32, bestLength int) (mnumOut, matchEndIdx uint32, bad bool)
