// btBody is the binary-tree finder (then lazyBody), instantiated once.
const btBody = `
// btSearch: btFindBestMatch (noDict) at DI = ip, R15 = p: nothing in the
// skipped area (curr < nextToUpdate), else dubtFindBestMatchAsm(p.bt, ip),
// which lazyBtRun's checks and btAsmSetup make valid for every ip of the
// block. Returns AX = ml (below 4: none; -1: a tree entry at or after the
// position sorted or searched, impossible), BX = offBase, SI = b. Clobbers
// everything but R15 (saved across the call, which loads its own p).
TEXT ·btSearch(SB), NOSPLIT, $40-0
	MOVL P_BASEIDX, CX
	ADDL DI, CX             // curr
	MOVQ P_NEXT, AX
	CMPL CX, (AX)
	JCS  skipped
	MOVQ R15, 32(SP)
	MOVQ P_BT, AX
	MOVQ AX, 0(SP)          // p
	MOVQ DI, 8(SP)          // ip
	CALL ·dubtFindBestMatchAsm(SB)
	MOVQ 32(SP), R15
	MOVQ 16(SP), AX         // bestLength
	MOVL 24(SP), BX         // offBase
	CMPB 28(SP), $0         // bad
	JEQ  found
	MOVQ $-1, AX

found:
	MOVQ P_B, SI
	RET

skipped:
	XORL AX, AX
	XORL BX, BX
	MOVQ P_B, SI
	RET
`

// hcBody is the hash-chain finder, instantiated once per mls (then lazyBody).
const hcBody = `
// hcSearch{{.Name}}: hcFindBestMatch (noDict, mls {{.M}}) at DI = ip, R15 = p,
// with insertAndFindFirstIndexInternal. Returns AX = ml (below 4: none; -1: a
// chain entry at or after ip, impossible), BX = offBase, SI = b. Clobbers
// everything but R15.
TEXT ·hcSearch{{.Name}}(SB), NOSPLIT, $16-0
	MOVQ P_B, R9
	MOVL P_BASEIDX, BX
	SUBQ BX, R9             // b - baseIdx: an index addresses b directly
	ADDL DI, BX             // curr
	MOVQ P_HASHTABLE, R10
	MOVQ P_CHAIN, R11
	MOVL P_CHAINMASK, R13
	MOVQ ${{.Prime}}, R14
	MOVQ P_HSHIFT, CX

	// insert [nextToUpdate, curr), or only nextToUpdate when lazy skipping
	// (C: ZSTD_insertAndFindFirstIndex_internal). nextToUpdate >= baseIdx
	// (lazyHcRun), and the 8 bytes hashed at each index lie before
	// ip + 8 <= iend.
	MOVQ P_NEXT, AX
	MOVL (AX), R8
	MOVL BX, SI             // the insert limit
	CMPL P_SKIP, $0
	JEQ  insck
	LEAL 1(R8), SI
	CMPL SI, BX
	JBE  insck
	MOVL BX, SI
	JMP  insck

ins:
	MOVQ  (R9)(R8*1), AX
	IMULQ R14, AX
	SHRQ  CX, AX
	MOVL  (R10)(AX*4), DX
	MOVL  R8, R12
	ANDL  R13, R12
	MOVL  DX, (R11)(R12*4)  // C: NEXT_IN_CHAIN(idx, chainMask) = hashTable[h]
	MOVL  R8, (R10)(AX*4)
	INCL  R8

insck:
	CMPL R8, SI
	JB   ins
	MOVQ P_NEXT, AX
	MOVL BX, (AX)           // nextToUpdate = curr
	MOVQ (R9)(BX*1), AX
	IMULQ R14, AX
	SHRQ CX, AX
	MOVL (R10)(AX*4), DX    // matchIndex

	// lowLimit = isDictionary ? lowestValid : withinMaxDistance
	MOVL P_LOWEST, R12
	MOVL BX, AX
	SUBL R12, AX
	CMPL AX, P_MAXDIST
	JLS  lowok
	MOVL BX, R12
	SUBL P_MAXDIST, R12

lowok:
	CMPL P_ISDICT, $0
	JEQ  lowset
	MOVL P_LOWEST, R12

lowset:
	// minChain = curr > chainSize ? curr - chainSize : 0
	XORL AX, AX
	MOVL BX, CX
	LEAL 1(R13), R10
	SUBL R10, CX
	CMOVLHI CX, AX
	MOVL AX, 0(SP)
	MOVL $0, 4(SP)          // best matchIndex
	MOVL P_ATTEMPTS, R14
	MOVQ P_ILIMIT, R8
	SUBQ DI, R8             // iLimit - ip
	MOVQ P_B, SI
	ADDQ SI, DI             // ip
	MOVL $3, AX             // ml
	MOVL (DI), CX           // read32(ip + ml - 3)

walk:
	CMPL DX, R12
	JB   done               // below lowLimit
	// Bounds: lowLimit <= DX < curr, and lowLimit >= baseIdx (lazyHcRun
	// checks lowestValid >= baseIdx and lowestValid <= ip's index, so
	// curr - lowestValid does not wrap). So R9 + DX lies in b[0:ip], and
	// the compare and count read only up to the iLimit - ip bytes b[ip:]
	// holds: match + ml + 1 <= ip + ml + 1, and ml < iLimit - ip here.
	CMPL DX, BX
	JAE  bad
	LEAQ (R9)(DX*1), R10
	CMPL CX, -3(R10)(AX*1)
	JNE  next
	// count (as fastCount): 8 bytes, then 32 per step with AVX2
	XORL SI, SI
	CMPQ R8, $8
	JB   cnttail
	MOVQ (R10), CX
	XORQ (DI), CX
	JNE  cntdiff
	MOVL $8, SI
	CMPB ·useAVX2(SB), $0
	JEQ  cnt8

cnt32:
	LEAQ 32(SI), CX
	CMPQ CX, R8
	JA   cnt32end
	VMOVDQU   (R10)(SI*1), Y0
	VPCMPEQB  (DI)(SI*1), Y0, Y0
	VPMOVMSKB Y0, CX
	INCL      CX
	JNE       cnt32diff
	ADDQ      $32, SI
	JMP       cnt32

cnt32diff:
	VZEROUPPER
	BSFL CX, CX
	ADDQ CX, SI
	JMP  cntdone

cnt32end:
	VZEROUPPER

cnt8:
	LEAQ 8(SI), CX
	CMPQ CX, R8
	JA   cnttail
	MOVQ (R10)(SI*1), CX
	XORQ (DI)(SI*1), CX
	JNE  cntdiff
	ADDQ $8, SI
	JMP  cnt8

cntdiff:
	BSFQ CX, CX
	SHRQ $3, CX
	ADDQ CX, SI
	JMP  cntdone

cnttail:
	CMPQ    SI, R8
	JAE     cntdone
	MOVBLZX (R10)(SI*1), CX
	CMPB    CX, (DI)(SI*1)
	JNE     cntdone
	INCQ    SI
	JMP     cnttail

cntdone:
	CMPQ SI, AX
	JLE  reload
	MOVQ SI, AX             // a longer match
	MOVL DX, 4(SP)
	CMPQ SI, R8
	JEQ  done               // best possible, avoids read overflow on next attempt

reload:
	MOVL -3(DI)(AX*1), CX

next:
	CMPL DX, 0(SP)
	JLS  done               // matchIndex <= minChain
	ANDL R13, DX
	MOVL (R11)(DX*4), DX    // C: NEXT_IN_CHAIN(matchIndex, chainMask)
	DECL R14
	JNE  walk

done:
	MOVQ P_B, SI
	CMPQ AX, $3
	JLE  none
	SUBL 4(SP), BX
	ADDL $3, BX             // offsetToOffBase(curr - matchIndex)
	RET

none:
	MOVL $999999999, BX     // offBaseNotFound
	RET

bad:
	MOVQ P_B, SI
	MOVQ $-1, AX
	RET
`

