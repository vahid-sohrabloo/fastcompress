// gen_row_amd64.go writes row_lazy_amd64.s: the row-based lazy parser
// (compressBlockLazyGeneric with searchRowHash) and its match finder in
// amd64 assembly, specialised per (mls, rowLog) like C's
// ZSTD_RowFindBestMatch_noDict_<mls>_<rowLog> and
// ZSTD_compressBlock_lazy*_row, so the hash shift and prime, rowLog,
// rowMask and the prefetch offsets are immediates. It also writes
// hc_lazy_amd64.s: the same lazy parser with the hash-chain finder
// (searchHashChain), specialised per mls like C's
// ZSTD_HcFindBestMatch_noDict_<mls>, and bt_lazy_amd64.s: the same lazy
// parser with the binary-tree finder (searchBinaryTree, btlazy2), which
// calls dubtFindBestMatchAsm (its mls is a run-time parameter).
//
//	go run gen_row_amd64.go
package main

import (
	"bytes"
	"fmt"
	"os"
	"strings"
	"text/template"
)

type spec struct {
	M, R    int    // mls, rowLog (R is unused by the hash-chain specs)
	Prime   string // hash: le64 * Prime, C's (le64 << shift) * prime with the shift folded in (as C does)
	Mask    int    // 1<<R - 1
	PfHash2 bool   // a hash row spans a second cache line (R >= 5)
	PfTag2  bool   // a tag row spans a second cache line (R == 6)
	Name    string
	Row     bool   // the row finder (row_lazy_amd64.s); false: the hash chain (hc_lazy_amd64.s)
	Lazy    string // the lazy parser's symbol
	Search  string // its finder's symbol
	Bt      bool   // the binary tree (bt_lazy_amd64.s)
}

func main() {
	primes := map[int]uint64{4: 2654435761, 5: 889523592379, 6: 227718039650203} // prime{4,5,6}bytes
	shifts := map[int]int{4: 32, 5: 64 - 40, 6: 64 - 48}
	prime := func(m int) string { return fmt.Sprintf("0x%x", primes[m]<<shifts[m]) } // (x << s) * p == x * (p << s) mod 2^64
	var rows, hcs []spec
	for m := 4; m <= 6; m++ {
		for r := 4; r <= 6; r++ {
			n := fmt.Sprintf("%d%d", m, r)
			rows = append(rows, spec{m, r, prime(m), 1<<r - 1, r >= 5, r == 6, n, true, "lazyRow" + n, "rowSearch" + n, false})
		}
		n := fmt.Sprint(m)
		hcs = append(hcs, spec{M: m, Prime: prime(m), Name: n, Lazy: "lazyHc" + n, Search: "hcSearch" + n})
	}
	write("row_lazy_amd64.s", rowBody+lazyBody, rows, footer)
	write("hc_lazy_amd64.s", hcBody+lazyBody, hcs, "")
	write("bt_lazy_amd64.s", btBody+lazyBody, []spec{{Bt: true, Lazy: "lazyBt", Search: "btSearch"}}, "")
}

func write(name, body string, specs []spec, footer string) {
	var out bytes.Buffer
	out.WriteString(header)
	t := template.Must(template.New("").Funcs(template.FuncMap{"mul": func(a, b int) int { return a * b }}).Parse(body))
	for _, s := range specs {
		if err := t.Execute(&out, s); err != nil {
			panic(err)
		}
	}
	out.WriteString(footer)
	src := strings.ReplaceAll(out.String(), "\n\n\n", "\n\n")
	if err := os.WriteFile(name, []byte(src), 0o644); err != nil {
		panic(err)
	}
}

