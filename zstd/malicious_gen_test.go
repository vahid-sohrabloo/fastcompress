		body := append(malCompLits(typ, 10, len(tree)+len(stream)), tree...)
		body = append(append(body, stream...), 0) // nbSeq 0
		return malFrame{hdr: malFHdr{single: true, fcsSize: 1, fcs: 10}.bytes(), blocks: []malBlock{malCBlock(body, true)}}.bytes()
