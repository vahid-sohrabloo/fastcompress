// cDecode runs C on data as c says to and returns its error (nil: decoded).
func cDecode(t *testing.T, c malCase, data []byte) *creftest.CError {
	t.Helper()
	args := []string{"-max-window-log", "29"}
	if c.dict != "" {
		p, err := filepath.Abs(filepath.Join("testdata", c.dict))
		if err != nil {
			t.Fatal(err)
		}
		args = append(args, "-dict", p)
		if c.rawDict {
			args = append(args, "-raw-dict", "1")
		}
	}
	if c.stream {
		// 7-byte input chunks: a whole frame is never in one chunk, so C
		// never takes ZSTD_decompressStream's single-pass shortcut (which
		// runs the one-shot path and skips the window check).
		_, e := creftest.DStreamCRef(t, data, append(args, "-chunk-size", "7", "-out-size", "4096")...)
		return e
	}
	_, e := creftest.DecodeCRef(t, data, args...)
	return e
}

func readManifest(t *testing.T) (lines []string, cErr map[string]string) {
	t.Helper()
	b, err := os.ReadFile(filepath.Join(malDir, malManifest))
	if err != nil {
		t.Fatalf("%v (run TestGenMalicious -update)", err)
	}
	cErr = map[string]string{}
	for _, l := range strings.Split(strings.TrimSuffix(string(b), "\n"), "\n") {
		if strings.HasPrefix(l, "#") {
			continue
		}
		lines = append(lines, l)
		file, rest, _ := strings.Cut(l, " ")
		_, rest, _ = strings.Cut(rest, " ")
		q, ok := strings.CutPrefix(rest, "C=")
		if !ok {
			t.Fatalf("manifest: bad line %q", l)
		}
		s, err := strconv.QuotedPrefix(q)
		if err != nil {
			t.Fatalf("manifest: bad line %q", l)
		}
		cErr[file], _ = strconv.Unquote(s)
	}
	return lines, cErr
}

// TestGenMalicious checks that the committed corpus is exactly what
// maliciousCases builds (with -update: rewrites it, recording C's errors).
func TestGenMalicious(t *testing.T) {
	cs := maliciousCases(t)
	cErr := map[string]string{}
	if *update {
		if err := os.MkdirAll(malDir, 0o755); err != nil {
			t.Fatal(err)
		}
		old, _ := filepath.Glob(filepath.Join(malDir, "*.zst"))
		for _, p := range old {
			if err := os.Remove(p); err != nil {
				t.Fatal(err)
			}
		}
		for _, c := range cs {
			e := cDecode(t, c, c.data)
			if e == nil {
				t.Fatalf("%s: C accepts it", c.name)
			}
			cErr[c.file()] = e.Name
			if !c.gen() {
				if err := os.WriteFile(filepath.Join(malDir, c.file()), c.data, 0o644); err != nil {
					t.Fatal(err)
				}
			}
		}
	} else {
		_, cErr = readManifest(t)
	}
	var m strings.Builder
	m.WriteString(malManifestHeader)
	for _, c := range cs {
		e, ok := cErr[c.file()]
		if !ok {
			t.Errorf("%s: not in %s (run TestGenMalicious -update)", c.file(), malManifest)
		}
		m.WriteString(c.manifestLine(e) + "\n")
	}
	mp := filepath.Join(malDir, malManifest)
	if *update {
		if err := os.WriteFile(mp, []byte(m.String()), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	if got, _ := os.ReadFile(mp); string(got) != m.String() {
		t.Errorf("%s differs from what maliciousCases builds (run TestGenMalicious -update)", mp)
	}
	want := map[string]bool{}
	for _, c := range cs {
		if c.gen() {
			continue
		}
		want[c.file()] = true
		got, err := os.ReadFile(filepath.Join(malDir, c.file()))
		if err != nil || !bytes.Equal(got, c.data) {
			t.Errorf("%s: committed file differs from what maliciousCases builds (err %v)", c.file(), err)
		}
	}
	files, _ := filepath.Glob(filepath.Join(malDir, "*.zst"))
	for _, p := range files {
		if !want[filepath.Base(p)] {
			t.Errorf("%s: not built by maliciousCases", p)
		}
	}
}

// TestMaliciousCorpusC checks that C v1.5.7 rejects every corpus input with
