// TestTruncationsCRef cuts frames of every type at every byte and checks
// that C rejects each prefix: one-shot with srcSize_wrong (checksum_wrong
// for a cut inside the checksum), streaming by ending mid-frame
// ("incomplete", which the decoder maps to io.ErrUnexpectedEOF). The
// one-shot decoder (truncCheck) must reject the same prefixes, with
// io.ErrUnexpectedEOF also for a cut inside the checksum (streaming C's
// answer, a deliberate deviation from one-shot C), and decode the prefixes
// that end at a part boundary.
func TestTruncationsCRef(t *testing.T) {
	creftest.Bin(t)
	text := malText(600)
	multi := func() []byte { // three blocks: flushes cut the stream
		var buf bytes.Buffer
		e, err := NewWriter(&buf, WithEncoderLevel(SpeedDefault))
		if err != nil {
			t.Fatal(err)
		}
		for _, part := range [][]byte{text[:200], text[200:400], text[400:]} {
			if _, err := e.Write(part); err != nil {
				t.Fatal(err)
			}
			if err := e.Flush(); err != nil {
				t.Fatal(err)
			}
		}
		if err := e.Close(); err != nil {
			t.Fatal(err)
		}
		return buf.Bytes()
	}()
	skip := binary.LittleEndian.AppendUint32(nil, 0x184D2A5F)
	skip = binary.LittleEndian.AppendUint32(skip, 20)
	skip = append(skip, malText(20)...)
	compressed := malEncode(t, text, false)
	cf := malParseFrame(t, compressed)
	dict, err := os.ReadFile(filepath.Join("testdata", "train.dict"))
	if err != nil {
		t.Fatal(err)
	}
	withDict := func() []byte {
		e, err := NewWriter(nil, WithEncoderLevel(SpeedDefault), WithEncoderDict(dict))
		if err != nil {
			t.Fatal(err)
		}
		return e.EncodeAll(text, nil)
	}()
	empty := func() []byte {
		e, err := NewWriter(nil, WithZeroFrames(true), WithEncoderCRC(false))
		if err != nil {
			t.Fatal(err)
		}
		return e.EncodeAll(nil, nil)
	}()
	type tframe struct {
		name  string
		parts [][]byte // concatenated; a cut at a part boundary is complete input
		c     malCase  // dictionary to load
	}
	frames := []tframe{
		{name: "empty", parts: [][]byte{empty}},
		{name: "raw", parts: [][]byte{malEncode(t, malRandom(7, 300), false)}},
		{name: "rle", parts: [][]byte{malEncode(t, make([]byte, 1000), true)}},
		{name: "compressed", parts: [][]byte{compressed}},
		{name: "compressed-checksum", parts: [][]byte{malEncode(t, text, true)}},
		{name: "multi-block", parts: [][]byte{multi}},
		{name: "skippable", parts: [][]byte{skip}},
		{name: "crafted-long-match", parts: [][]byte{craftFrame(craftBlock(t, []byte("abcd"), []malSeq{{4, 1000, 4}}))}},
		{name: "concatenated", parts: [][]byte{compressed, skip, malEncode(t, text[:300], true), empty}},
		{name: "dictid", parts: [][]byte{withDict}, c: malCase{dict: "train.dict"}},
		{name: "fcs8", parts: [][]byte{cf.with(malFHdr{winDesc: malWindow1M, fcsSize: 8, fcs: 600}.bytes(), -1, malBlock{})}},
		{name: "windowed-fcs2", parts: [][]byte{cf.with(malFHdr{winDesc: malWindow1M, fcsSize: 2, fcs: 600}.bytes(), -1, malBlock{})}},
	}
	if fhd := withDict[4]; fhd&3 == 0 {
		t.Fatal("dictid: the dictionary frame has no dictID field")
	}
	for _, f := range frames {
		if e := cDecode(t, f.c, bytes.Join(f.parts, nil)); e != nil {
			t.Fatalf("%s: C rejects the whole input: %v", f.name, e)
		}
	}
	for _, f := range frames {
		t.Run(f.name, func(t *testing.T) {
			t.Parallel()
			data := bytes.Join(f.parts, nil)
			// complete[n]: data[:n] ends at a part boundary; inCksum[n]:
			// data[:n] ends inside (or right before) a frame checksum.
			complete, inCksum := map[int]bool{}, map[int]bool{}
			pos := 0
			for _, p := range f.parts {
				pos += len(p)
				complete[pos] = true
				if binary.LittleEndian.Uint32(p) == 0xFD2FB528 && p[4]&4 != 0 {
					for n := pos - 4; n < pos; n++ {
						inCksum[n] = true
					}
				}
			}
			stream := f.c
			stream.stream = true
			var dd *ddict
			if f.c.dict != "" {
				dd = mustDDict(t, readTestdata(t, f.c.dict), f.c.rawDict)
			}
			var wants [][]byte
			for _, p := range f.parts {
				w, err := newDCtx().decompressMultiFrame(nil, p, dd)
				if err != nil {
					t.Fatal(err)
				}
				wants = append(wants, w)
			}
			truncCheck(t, f.parts, wants, dd)
			names := map[string]int{}
			for n := 1; n < len(data); n++ {
				cut := data[:n]
				e := cDecode(t, f.c, cut)
				if complete[n] {
					if e != nil {
						t.Fatalf("cut at part boundary %d: C one-shot rejects it: %v", n, e)
					}
					continue
				}
				if e == nil {
					t.Fatalf("cut at %d/%d: C one-shot accepts it", n, len(data))
				}
				names[e.Name]++
				// C's one-shot path reports a cut inside the checksum as
				// checksum_wrong (ZSTD_decompressFrame: remainingSrcSize < 4).
				if e.Name != "Src size is incorrect" && !(inCksum[n] && e.Name == "Restored data doesn't match checksum") {
					t.Errorf("cut at %d/%d: C one-shot error %q", n, len(data), e.Name)
				}
				if e := cDecode(t, stream, cut); e == nil || e.Name != "incomplete" {
					t.Fatalf("cut at %d/%d: C streaming returns %v, want incomplete", n, len(data), e)
				}
			}
			t.Logf("%d cuts; C one-shot errors: %v", len(data)-1, names)
		})
	}
}

// TestTrailingGarbageCRef pins how C reports bytes with a bad magic after
// the input's frames. One-shot C (ZSTD_decompressMultiFrame) reports
// prefix_unknown only when no zstd frame has completed yet (skippable
// frames do not count): after a real frame it reports srcSize_wrong
// ("following bytes are garbage"). Streaming C reports prefix_unknown
// either way. Fewer than 9 trailing bytes are srcSize_wrong one-shot (too
// short for a frame header plus block header).
func TestTrailingGarbageCRef(t *testing.T) {
	creftest.Bin(t)
	frame := malEncode(t, malText(600), false)
	skip := binary.LittleEndian.AppendUint32(nil, 0x184D2A50)
	skip = binary.LittleEndian.AppendUint32(skip, 4)
	skip = append(skip, "skip"...)
	garbage := []byte("bad!magic number")
	const (
		srcSizeWrong  = "Src size is incorrect"
		prefixUnknown = "Unknown frame descriptor"
	)
	for _, tc := range []struct {
		name             string
		data             []byte
		oneShot, dstream string
	}{
		{"alone", garbage, prefixUnknown, prefixUnknown},
		{"after-frame", append(append([]byte(nil), frame...), garbage...), srcSizeWrong, prefixUnknown},
		{"after-frame-and-skippable", bytes.Join([][]byte{frame, skip, garbage}, nil), srcSizeWrong, prefixUnknown},
		{"after-skippable", append(append([]byte(nil), skip...), garbage...), prefixUnknown, prefixUnknown},
		{"after-frame-8-bytes", append(append([]byte(nil), frame...), garbage[:8]...), srcSizeWrong, prefixUnknown},
	} {
		t.Run(tc.name, func(t *testing.T) {
			if e := cDecode(t, malCase{}, tc.data); e == nil || e.Name != tc.oneShot {
				t.Errorf("C one-shot: %v, want %q", e, tc.oneShot)
			}
			if e := cDecode(t, malCase{stream: true}, tc.data); e == nil || e.Name != tc.dstream {
				t.Errorf("C streaming: %v, want %q", e, tc.dstream)
			}
		})
	}
}

// malRandom returns n deterministic incompressible bytes.
func malRandom(seed uint64, n int) []byte {
	b := make([]byte, n)
	x := seed*0x9E3779B97F4A7C15 + 1
	for i := range b {
		x ^= x << 13
		x ^= x >> 7
		x ^= x << 17
		b[i] = byte(x >> 56)
	}
	return b
}
