// The malicious decode corpus: inputs built by byte surgery on valid frames
// (from this package's encoder, or assembled from hand-written sections),
// each aimed at one check the decoder must make before it trusts a value
// read from the input. TestGenMalicious (-update) writes them to
// testdata/decode/malicious with MANIFEST.txt; TestMaliciousCorpusC checks
// that C v1.5.7 rejects every one, with the error recorded in the manifest.

var updateMalBase = flag.Bool("update-mal-base", false,
	"rebuild the malicious corpus's base fixtures with the encoder (TestGenMalicious)")

const (
	malDir      = "testdata/decode/malicious"
	malBaseDir  = malDir + "/base"
	malManifest = "MANIFEST.txt"
	// malCommitMax is the largest case committed as a file; larger cases
	// are built in memory by maliciousCases and listed as gen:<name>.
	malCommitMax = 8 << 10
)

// malCase is one malicious input.
type malCase struct {
	name   string // file name without .zst
	expect string // the Go sentinel's name, "corrupt" (no sentinel) or "unexpected-eof"
	desc   string // what it targets and how it was made
	data   []byte
	// control is data without the defect; C must decode it. It shows that
	// the surgery, not the rest of the construction, is what C rejects.
	// nil when no meaningful defect-free variant exists.
	control []byte
	dict    string // testdata file loaded as the dictionary ("" none)
	rawDict bool   // load dict as raw content (else zstd dictionary format)
	stream  bool   // C checks it with ZSTD_decompressStream (cref dstream)
}

func (c malCase) gen() bool { return len(c.data) > malCommitMax }

func (c malCase) file() string {
	if c.gen() {
		return "gen:" + c.name
	}
	return c.name + ".zst"
}

// manifestLine is c's MANIFEST.txt line; cErr is C's ZSTD_getErrorName for
// it (or "incomplete").
func (c malCase) manifestLine(cErr string) string {
	var tags []string
	if c.stream {
		tags = append(tags, "dstream")
	}
	if c.dict != "" && c.rawDict {
		tags = append(tags, "raw-dict="+c.dict)
	} else if c.dict != "" {
		tags = append(tags, "dict="+c.dict)
	}
	t := ""
	if len(tags) > 0 {
		t = "[" + strings.Join(tags, " ") + "] "
	}
	return fmt.Sprintf("%s %s C=%q %s%s", c.file(), c.expect, cErr, t, c.desc)
}

