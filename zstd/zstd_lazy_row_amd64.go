// lazyRowExtRun runs compressBlockLazyExtDictGeneric's match loop (row
// finder) in assembly from ip until ilimit, storing into ss, and returns
// the new ip, anchor and repcodes. It returns ok = false, doing nothing,
// when the assembly is off or a precondition fails: those of lazyRowRun
// (for the prefix, with rowAsmSetup's checks but lowLimit's), and for the
// extDict (zstd_lazy_gen_row_amd64.go's EXTDICT): dictBaseIdx <=
// lowLimit < dictLimit, baseIdx <= dictLimit <= ip's index, and
// dictLimit - dictBaseIdx <= len(window.dictBase).
func lazyRowExtRun(ms *matchState, ss *seqStore, ip, anchor, iend, ilimit int,
	offset1, offset2 uint32, depth int, mls, rowLog uint32) (int, int, uint32, uint32, bool) {
	w := &ms.window
	b, d := w.base, w.dictBase
	rows := 1 << (ms.rowHashLog + rowLog)
	if !useRowAsm || rowLog < 4 || rowLog > 6 || mls < 4 || mls > 6 || len(ms.hashTable) < rows || len(ms.tagTable) < rows ||
		iend > len(b) || len(b) == 0 || len(d) == 0 || w.lowLimit < w.dictBaseIdx || w.lowLimit >= w.dictLimit ||
		w.dictLimit < w.baseIdx || w.dictLimit > uint32(ip)+w.baseIdx || int(w.dictLimit-w.dictBaseIdx) > len(d) {
		return ip, anchor, offset1, offset2, false
	}
	p := &ms.rowAsm
	m := mls & 15
	cParams := &ms.cParams
	*p = rowAsmParams{
		hashTable:    &ms.hashTable[0],
		tagTable:     &ms.tagTable[0],
		b:            &b[0],
		cache:        &ms.hashCache,
		nextToUpdate: &ms.nextToUpdate,
		entropy:      &ms.hashSaltEntropy,
		hShift:       uint64(64 - (ms.rowHashLog + rowHashTagBits)),
		saltAdj:      ms.hashSalt << saltedHashSaltShift[m],
		baseIdx:      w.baseIdx,
		nbAttempts:   1 << min(cParams.searchLog, rowLog),
		lowestValid:  w.lowLimit,
		maxDistance:  1 << cParams.windowLog,
		bLen:         iend,
		iLimit:       iend,
		dictBase:     &d[0],
		dictBaseIdx:  w.dictBaseIdx,
		dictLimit:    w.dictLimit,
	}
	if ms.loadedDictEnd != 0 {
		p.isDictionary = 1
	}
	// Do not keep the window and tables reachable through ms.rowAsm once
	// the block is done.
	defer func() { ms.rowAsm = rowAsmParams{} }()
	nLits, nSeqs := len(ss.literals), len(ss.sequences)
	if ip <= 0 || anchor > ip || ilimit+16 > iend || ms.nextToUpdate > uint32(ip)+p.baseIdx || ms.nextToUpdate < p.baseIdx ||
		depth < 0 || depth > 2 || cap(ss.literals)-nLits < iend-anchor+16 || cap(ss.sequences)-nSeqs < (iend-anchor)/4 {
		return ip, anchor, offset1, offset2, false
	}
	seqs := ss.sequences[nSeqs:cap(ss.sequences)]
	lits := ss.literals[nLits:cap(ss.literals)]
	var seqPtr *seqDef
	if len(seqs) > 0 {
		seqPtr = &seqs[0]
	}
	var litPtr *byte
	if len(lits) > 0 {
		litPtr = &lits[0]
	}
	p.skip = 0
	if ms.lazySkipping {
		p.skip = 1
	}
	f := lazyRowExtFuncs[(mls-4)*3+rowLog-4]
	ipOut, anchorOut, nSeq, nLit, r1, r2, llType, llPos := f(p, seqPtr, litPtr, ip, anchor, iend, ilimit, 0, offset1, offset2, depth)
	if nSeq < 0 {
		panic("zstd: row table holds an index at or after the current position, or in the extDict's last 3 bytes")
	}
	ms.asmLoopRuns++
	ms.lazySkipping = p.skip != 0
	ss.sequences = ss.sequences[:nSeqs+nSeq]
	ss.literals = ss.literals[:nLits+nLit]
	if llType != lltNone {
		ss.longLengthType = int(llType)
		ss.longLengthPos = uint32(nSeqs) + llPos
	}
	return ipOut, anchorOut, r1, r2, true
}
